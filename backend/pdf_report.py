"""
    Building the printable shift record PDF
"""
import io
import os
import re
from datetime import date, datetime, timedelta

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import inch
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.pdfgen import canvas as pdfcanvas
from reportlab.platypus import (BaseDocTemplate, Flowable, Frame, KeepTogether,
                                PageTemplate, Paragraph, Spacer, Table, TableStyle)

# Fira Code is monospace, so every character advances the same distance
# regardless of weight. Column widths below are sized from that fixed
# advance rather than guessed, which is what keeps this table lining up.
FONTS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fonts")
pdfmetrics.registerFont(TTFont("FiraCode", os.path.join(FONTS_DIR, "FiraCode-Regular.ttf")))
pdfmetrics.registerFont(TTFont("FiraCode-Bold", os.path.join(FONTS_DIR, "FiraCode-Bold.ttf")))

REGULAR = "FiraCode"
BOLD = "FiraCode-Bold"
CHAR_W = pdfmetrics.stringWidth("0", REGULAR, 11)   # monospace: every glyph is this wide at 11pt

INK = colors.HexColor("#141414")
MUTED = colors.HexColor("#6f6f6f")
FOOTER_GRAY = colors.HexColor("#9a9a9a")            # lighter than MUTED: the footer credit line reads greyer still
RULE = colors.HexColor("#111111")
HAIRLINE = colors.HexColor("#dcdcdc")

MARGIN = 0.85 * inch
FOOTER_BAND = 0.85 * inch
BODY_SIZE = 11
FOOTER_SIZE = 7.5
LEADING = BODY_SIZE * 1.35

TITLE = ParagraphStyle("title", fontName=BOLD, fontSize=BODY_SIZE, leading=LEADING, textColor=INK)
DOCMETA = ParagraphStyle("docmeta", fontName=REGULAR, fontSize=BODY_SIZE, leading=LEADING,
                         textColor=MUTED, alignment=2)
LABEL = ParagraphStyle("label", fontName=BOLD, fontSize=BODY_SIZE, leading=LEADING, textColor=MUTED)
VALUE = ParagraphStyle("value", fontName=REGULAR, fontSize=BODY_SIZE, leading=LEADING, textColor=INK)
BODY = ParagraphStyle("body", fontName=REGULAR, fontSize=BODY_SIZE, leading=LEADING, textColor=INK)
CAPTION = ParagraphStyle("caption", fontName=BOLD, fontSize=BODY_SIZE, leading=LEADING, textColor=MUTED)
CAPTION_CENTER = ParagraphStyle("caption_center", parent=CAPTION, alignment=TA_CENTER)


def shift_hours(start, end):
    """Length of a shift in hours, treating an end before the start as an overnight shift."""
    if start is None or end is None:
        return 0.0
    span = datetime.combine(date.min, end) - datetime.combine(date.min, start)
    if span < timedelta(0):
        span += timedelta(days=1)
    return span.total_seconds() / 3600


def _phone(number):
    digits = re.sub(r'\D', '', number or "")
    if len(digits) == 10:
        return "(%s) %s-%s" % (digits[:3], digits[3:6], digits[6:])
    return number or "—"


def _chars(n):
    """Column width, in points, for n monospace characters at the body size."""
    return n * CHAR_W


class HRule(Flowable):
    """A plain horizontal rule — the document is built from rules, not boxes."""

    def __init__(self, width, thickness=0.7, colour=RULE, space_before=0, space_after=0):
        Flowable.__init__(self)
        self.width = width
        self.thickness = thickness
        self.colour = colour
        self.space_before = space_before
        self.space_after = space_after

    def wrap(self, available_width, available_height):
        return self.width, self.thickness + self.space_before + self.space_after

    def draw(self):
        self.canv.setStrokeColor(self.colour)
        self.canv.setLineWidth(self.thickness)
        self.canv.line(0, self.space_after, self.width, self.space_after)


def _draw_furniture(canv, page_num, page_total, heading):
    """The page-bottom furniture: a hairline and the attribution line."""
    width, height = letter
    baseline = MARGIN * 0.62

    canv.saveState()
    canv.setStrokeColor(HAIRLINE)
    canv.setLineWidth(0.6)
    canv.line(MARGIN, baseline + 14, width - MARGIN, baseline + 14)

    canv.setFillColor(FOOTER_GRAY)
    canv.setFont(REGULAR, FOOTER_SIZE)
    canv.drawString(MARGIN, baseline, "Generated by the EZ-VolunteerSys management system")
    canv.restoreState()

    # Continuation pages carry a running head so a loose sheet is still identifiable.
    if page_num > 1:
        canv.saveState()
        canv.setFillColor(FOOTER_GRAY)
        canv.setFont(REGULAR, FOOTER_SIZE)
        canv.drawString(MARGIN, height - MARGIN + 14, heading)
        canv.drawRightString(width - MARGIN, height - MARGIN + 14, "continued")
        canv.setStrokeColor(HAIRLINE)
        canv.setLineWidth(0.6)
        canv.line(MARGIN, height - MARGIN + 8, width - MARGIN, height - MARGIN + 8)
        canv.restoreState()


class _NumberedCanvas(pdfcanvas.Canvas):
    """Defers every page so the running head knows it isn't the first page."""

    def __init__(self, *args, **kwargs):
        self._heading = kwargs.pop("heading", "")
        super().__init__(*args, **kwargs)
        self._pages = []

    def showPage(self):
        self._pages.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        total = len(self._pages)
        for page_num, state in enumerate(self._pages, start=1):
            self.__dict__.update(state)
            _draw_furniture(self, page_num, total, self._heading)
            super().showPage()
        super().save()


def _masthead(volunteer, generated, width):
    head = Table([[
        Paragraph("VOLUNTEER SHIFT RECORD", TITLE),
        Paragraph(generated.strftime("%d %B %Y"), DOCMETA),
    ]], colWidths=[width * 0.55, width * 0.45])
    head.setStyle(TableStyle([
        ("VALIGN", (0, 0), (0, 0), "BOTTOM"),
        ("VALIGN", (1, 0), (1, 0), "BOTTOM"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
    ]))
    return head


def _particulars(volunteer, width):
    """Two label/value pairs per row, with the address given the full measure underneath."""
    rows = [
        [Paragraph("VOLUNTEER", LABEL), Paragraph(volunteer.Fullname.title(), VALUE), "", ""],
        [Paragraph("PHONE", LABEL), Paragraph(_phone(volunteer.PhoneNum), VALUE),
         Paragraph("REGISTERED BY", LABEL), Paragraph((volunteer.Admin or "—").title(), VALUE)],
        [Paragraph("ADDRESS", LABEL), Paragraph((volunteer.Address or "—").title(), VALUE), "", ""],
    ]

    # "REGISTERED BY" is 13 characters; the extra headroom below covers the column's own padding.
    label_w = _chars(16)
    value_w = (width - 2 * label_w) / 2
    table = Table(rows, colWidths=[label_w, value_w, label_w, value_w])
    table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("SPAN", (1, 0), (3, 0)),
        ("SPAN", (1, 2), (3, 2)),
    ]))
    return table


def _shift_table(shifts, total_hours, width):
    head = ["", "DATE", "START", "END", "HOURS", "SIGNED OFF BY"]
    rows = [head]
    for index, shift in enumerate(shifts, start=1):
        rows.append([
            str(index),
            shift.Date.strftime("%d %b %Y") if shift.Date else "—",
            shift.Start.strftime("%H:%M") if shift.Start else "—",
            shift.End.strftime("%H:%M") if shift.End else "—",
            "{0:.2f}".format(shift_hours(shift.Start, shift.End)),
            (shift.Admin or "—").title(),
        ])
    rows.append(["", "Total hours logged", "", "", "{0:.2f}".format(total_hours), ""])

    # Sized in characters, not guessed inches: "18 Aug 2026" is 11 chars, "09:00" is 5, and
    # so on. Each column carries two extra characters of headroom beyond its widest real
    # value, since RIGHTPADDING below only adds visual polish and isn't relied on for fit.
    num_w = _chars(3)
    date_w = _chars(14)
    time_w = _chars(8)
    hours_w = _chars(8)
    last_col = width - num_w - date_w - 2 * time_w - hours_w
    widths = [num_w, date_w, time_w, time_w, hours_w, last_col]
    table = Table(rows, colWidths=widths, repeatRows=1)

    last = len(rows) - 1
    style = [
        ("FONTNAME", (0, 0), (-1, 0), BOLD),
        ("FONTSIZE", (0, 0), (-1, 0), BODY_SIZE),
        ("TEXTCOLOR", (0, 0), (-1, 0), MUTED),
        ("FONTNAME", (0, 1), (-1, -1), REGULAR),
        ("FONTSIZE", (0, 1), (-1, -1), BODY_SIZE),
        ("TEXTCOLOR", (0, 1), (-1, -1), INK),
        ("TEXTCOLOR", (0, 1), (0, -1), MUTED),
        ("ALIGN", (0, 0), (0, -1), "RIGHT"),
        ("ALIGN", (2, 0), (4, -1), "RIGHT"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (0, -1), 0),
        ("RIGHTPADDING", (0, 0), (0, -1), 9),
        ("LEFTPADDING", (1, 0), (-1, -1), 0),
        ("RIGHTPADDING", (1, 0), (-2, -1), 10),
        ("RIGHTPADDING", (-1, 0), (-1, -1), 0),
        ("TOPPADDING", (0, 0), (-1, 0), 0),
        ("BOTTOMPADDING", (0, 0), (-1, 0), 6),
        ("TOPPADDING", (0, 1), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 1), (-1, -1), 6),
        # Rules only: one under the column heads, hairlines between entries, one above the total.
        ("LINEBELOW", (0, 0), (-1, 0), 0.7, RULE),
        ("LINEBELOW", (0, 1), (-1, last - 2), 0.4, HAIRLINE),
        ("LINEABOVE", (0, last), (-1, last), 0.7, RULE),
        ("FONTNAME", (1, last), (1, last), BOLD),
        ("TEXTCOLOR", (1, last), (1, last), MUTED),
        ("FONTNAME", (4, last), (4, last), BOLD),
        ("TOPPADDING", (0, last), (-1, last), 8),
        ("VALIGN", (0, last), (-1, last), "BOTTOM"),
    ]
    table.setStyle(TableStyle(style))
    return table


def _signoff_block(width):
    """Signature, date, and an organisation stamp box, left to right along the bottom."""
    gap = _chars(2)
    stamp_w = _chars(22)
    date_w = _chars(16)
    sig_w = width - stamp_w - date_w - 2 * gap

    table = Table([
        [" ", "", " ", "", ""],
        [Paragraph("AUTHORISED SIGNATURE", CAPTION), "",
         Paragraph("DATE", CAPTION), "",
         Paragraph("Organization Stamp (if applicable)", CAPTION_CENTER)],
    ], colWidths=[sig_w, gap, date_w, gap, stamp_w], rowHeights=[64, None])

    table.setStyle(TableStyle([
        ("LINEABOVE", (0, 1), (0, 1), 0.6, RULE),
        ("LINEABOVE", (2, 1), (2, 1), 0.6, RULE),
        ("BOX", (4, 0), (4, 0), 0.7, RULE),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("TOPPADDING", (0, 1), (-1, 1), 4),
        ("VALIGN", (0, 0), (-1, 0), "TOP"),
        ("VALIGN", (0, 1), (-1, 1), "TOP"),
    ]))
    return table


def build_shift_report(volunteer, shifts):
    """Render the volunteer's full shift history and return the PDF as bytes."""
    generated = datetime.now()
    buffer = io.BytesIO()
    width = letter[0] - 2 * MARGIN
    name = volunteer.Fullname.title()

    doc = BaseDocTemplate(buffer, pagesize=letter,
                          leftMargin=MARGIN, rightMargin=MARGIN,
                          topMargin=MARGIN, bottomMargin=FOOTER_BAND,
                          title="Volunteer Shift Record - " + name,
                          author="EZ-Volunteer System")
    frame = Frame(MARGIN, doc.bottomMargin, width, letter[1] - MARGIN - doc.bottomMargin,
                  id="body", leftPadding=0, rightPadding=0, topPadding=0, bottomPadding=0)
    doc.addPageTemplates([PageTemplate(id="report", frames=[frame])])

    total_hours = sum(shift_hours(shift.Start, shift.End) for shift in shifts)

    story = [
        _masthead(volunteer, generated, width),
        Spacer(1, 7),
        HRule(width, thickness=1.1),
        Spacer(1, 9),
        _particulars(volunteer, width),
        Spacer(1, 5),
        HRule(width, thickness=0.4, colour=HAIRLINE),
        Spacer(1, 20),
    ]

    if shifts:
        story.append(_shift_table(shifts, total_hours, width))
        # Nothing to attest to on an empty record, so the sign-off block is withheld.
        # KeepTogether stops the table from splitting mid-row at a page break, which
        # would otherwise strand the stamp box and signature line on the prior page
        # while their captions land on the next one.
        story.append(Spacer(1, 30))
        story.append(KeepTogether([
            Paragraph("I confirm the hours recorded above are a true account of service given.", BODY),
            Spacer(1, 16),
            _signoff_block(width),
        ]))
    else:
        story.append(Paragraph("No shifts have been logged for this volunteer yet.", BODY))

    doc.build(story, canvasmaker=lambda *a, **kw: _NumberedCanvas(
        *a, heading="Volunteer Shift Record — " + name, **kw))
    return buffer.getvalue()
